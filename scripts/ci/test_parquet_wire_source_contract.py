"""Pin every generated Parquet Thrift declaration to its upstream source."""

import hashlib
import re
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "crates/alopex-sql/src/executor/bulk/parquet/wire_schema/format.rs"
GOLDENS = ROOT / "crates/alopex-sql/src/executor/bulk/parquet/wire_schema/golden_tests.rs"
UPSTREAM_SHA256 = "14fa0958710481a9616e902a32991baa3e998f69a5b0d07f4002a286fa59273f"
UPSTREAM_DOC = "//! See [`crate::file`] for easier to use APIs.\n"
GENERATED_MARKER = "// Autogenerated by Thrift Compiler (0.21.0)\n"
PINNED_TRAIT = "impl super::TSerializable for "
UPSTREAM_TRAIT = "impl crate::thrift::TSerializable for "


class ParquetWireSourceContractTests(unittest.TestCase):
    def test_all_generated_declarations_match_upstream_57_3_2(self):
        source = SOURCE.read_text()
        self.assertEqual(source.count(GENERATED_MARKER), 1)
        self.assertEqual(source.count(PINNED_TRAIT), 66)
        # Only the documented header and trait path changes are permitted.
        generated = source[source.index(GENERATED_MARKER) :]
        restored = UPSTREAM_DOC + generated.replace(PINNED_TRAIT, UPSTREAM_TRAIT)
        self.assertEqual(hashlib.sha256(restored.encode()).hexdigest(), UPSTREAM_SHA256)

    def test_every_serializable_type_has_one_generated_implementation(self):
        source = SOURCE.read_text()
        declarations = re.findall(r"^pub (?:struct|enum) (\w+)(?:\b|\()", source, re.MULTILINE)
        implementations = re.findall(r"^impl super::TSerializable for (\w+) \{", source, re.MULTILINE)
        self.assertEqual(len(declarations), 66)
        self.assertEqual(sorted(declarations), sorted(implementations))

    def test_golden_registry_covers_all_types_variants_and_optional_modes(self):
        source = SOURCE.read_text()
        cases = re.findall(r'check::<format::(\w+)>\s*\(\s*"(\w+)\.(\w+)"', GOLDENS.read_text())
        self.assertEqual(len(cases), 163)
        self.assertEqual(len(cases), len(set(cases)))
        by_type = {}
        for generic, named, case in cases:
            self.assertEqual(generic, named)
            by_type.setdefault(named, set()).add(case)
        declarations = set(re.findall(r"^pub (?:struct|enum) (\w+)(?:\b|\()", source, re.MULTILINE))
        self.assertEqual(set(by_type), declarations)
        for name, body in re.findall(r"^pub struct (\w+) \{(.*?)^\}", source, re.MULTILINE | re.DOTALL):
            expected = {"required"}
            if re.search(r"^\s+pub \w+: Option<", body, re.MULTILINE):
                expected.add("all_present")
            self.assertEqual(by_type[name], expected, name)
        for name, body in re.findall(r"^pub enum (\w+) \{(.*?)^\}", source, re.MULTILINE | re.DOTALL):
            variants = set(re.findall(r"^\s+(\w+)\(\w+\),$", body, re.MULTILINE))
            self.assertEqual(by_type[name], variants, name)
        for name in re.findall(r"^pub struct (\w+)\(pub i32\);", source, re.MULTILINE):
            block = re.search(r"^impl " + name + r" \{(.*?)^\}", source, re.MULTILINE | re.DOTALL).group(1)
            values = set(re.findall(r"pub const (\w+): " + name + r" =", block))
            self.assertEqual(by_type[name], values, name)


if __name__ == "__main__":
    unittest.main()
