fn check<T: TSerializable + Debug + PartialEq>(name: &str, bytes: &[u8]) {
    let mut protocol = TCompactInputProtocol::new(Cursor::new(bytes));
    let decoded =
        T::read_from_in_protocol(&mut protocol).unwrap_or_else(|error| panic!("{name}: {error}"));
    let mut rewritten = Vec::new();
    decoded
        .write_to_out_protocol(&mut TCompactOutputProtocol::new(&mut rewritten))
        .unwrap();
    assert_eq!(rewritten, bytes, "{name}");
    CASES.fetch_add(1, Ordering::Relaxed);
}

