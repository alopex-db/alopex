//! Pinned wire declarations used after the allocation preflight.
//!
//! Keep these types private: decoding and compression use the current Parquet
//! crate. See README.md for the upstream source and update procedure.

use thrift::protocol::{TInputProtocol, TOutputProtocol};

// Preserve the upstream generated declarations without formatting/lint churn.
#[allow(clippy::all, missing_docs)]
#[rustfmt::skip]
pub mod format;

/// The generic serialization interface used by the upstream wire declarations.
pub trait TSerializable: Sized {
    fn read_from_in_protocol<T: TInputProtocol>(protocol: &mut T) -> thrift::Result<Self>;
    fn write_to_out_protocol<T: TOutputProtocol>(&self, protocol: &mut T) -> thrift::Result<()>;
}

#[cfg(test)]
mod tests {
    use super::TSerializable;
    use super::format::{FileMetaData, KeyValue, SortingColumn, Statistics};
    use sha2::{Digest, Sha256};
    use std::fmt::Debug;
    use std::io::Cursor;
    use thrift::protocol::{TCompactInputProtocol, TCompactOutputProtocol};

    fn roundtrip<T: TSerializable + Debug + PartialEq>(value: T) {
        let mut encoded = Vec::new();
        value
            .write_to_out_protocol(&mut TCompactOutputProtocol::new(&mut encoded))
            .unwrap();
        let mut input = TCompactInputProtocol::new(Cursor::new(encoded.as_slice()));
        let decoded = T::read_from_in_protocol(&mut input).unwrap();
        assert_eq!(decoded, value);
        let mut rewritten = Vec::new();
        decoded
            .write_to_out_protocol(&mut TCompactOutputProtocol::new(&mut rewritten))
            .unwrap();
        assert_eq!(rewritten, encoded);
    }

    #[test]
    fn generated_wire_declarations_match_upstream_57_3_2() {
        const MARKER: &str = "// Autogenerated by Thrift Compiler (0.21.0)\n";
        const PINNED: &str = "impl super::TSerializable for ";
        const UPSTREAM: &str = "impl crate::thrift::TSerializable for ";
        let source = include_str!("format.rs");
        assert_eq!(source.matches(MARKER).count(), 1);
        assert_eq!(source.matches(PINNED).count(), 66);
        let generated = &source[source.find(MARKER).unwrap()..];
        let restored = format!(
            "//! See [`crate::file`] for easier to use APIs.\n{}",
            generated.replace(PINNED, UPSTREAM)
        );
        assert_eq!(
            format!("{:x}", Sha256::digest(restored.as_bytes())),
            "14fa0958710481a9616e902a32991baa3e998f69a5b0d07f4002a286fa59273f"
        );
    }

    #[test]
    fn metadata_examples_roundtrip_under_current_thrift() {
        roundtrip(Statistics::default());
        roundtrip(Statistics::new(
            Some(vec![9]),
            Some(vec![1]),
            Some(0),
            Some(2),
            Some(vec![8]),
            Some(vec![2]),
            Some(true),
            Some(false),
        ));
        roundtrip(SortingColumn::new(2, true, false));
        roundtrip(FileMetaData::new(
            2,
            Vec::new(),
            3,
            Vec::new(),
            Some(vec![KeyValue::new("creator".into(), Some("test".into()))]),
            Some("alopex-test".into()),
            None,
            None,
            Some(vec![1, 2, 3]),
        ));
    }
}
